# ------------------------------------------------------------------ limit and min_similarity
def test_the_limit_defaults_to_five_and_is_respected(client, auth_headers, admin, enrolled, query_image):
    for index in range(6):
        enrolled(f"Candidate {index}", [[1, index / 10, 0, 0]])
    assert len(_search(client, auth_headers, admin, query_image).json()["results"]) == 5        # SEARCH_DEFAULT_LIMIT
    two = _search(client, auth_headers, admin, query_image, limit=2).json()["results"]
    assert [item["case"]["name"] for item in two] == ["Candidate 0", "Candidate 1"]
    assert len(_search(client, auth_headers, admin, query_image, limit=20).json()["results"]) == 6


def test_a_limit_outside_1_to_the_maximum_is_a_422(client, auth_headers, admin, query_image, fake_recognition):
    for bad in ("0", "-1", "21", "101", "abc"):
        response = _search(client, auth_headers, admin, query_image, limit=bad)
        assert response.status_code == 422, bad
        assert any("limit" in error["field"] for error in response.json()["error"]["fields"]), bad
    assert "abc" not in str(_search(client, auth_headers, admin, query_image, limit="abc").json())   # input is not echoed
    assert fake_recognition.calls == []                                           # refused before any work was done


def test_min_similarity_is_optional_and_filters_the_candidates(client, auth_headers, admin, enrolled, query_image):
    enrolled("High Fictional", [[0.8, 0.6, 0, 0]])
    enrolled("Middle Fictional", [[0.5, 0.8660254, 0, 0]])
    enrolled("Low Fictional", [[0, 1, 0, 0]])
    names = lambda response: [item["case"]["name"] for item in response.json()["results"]]       # noqa: E731
    assert names(_search(client, auth_headers, admin, query_image)) == ["High Fictional", "Middle Fictional", "Low Fictional"]
    assert names(_search(client, auth_headers, admin, query_image, min_similarity=0.5)) == ["High Fictional", "Middle Fictional"]
    assert names(_search(client, auth_headers, admin, query_image, min_similarity=0.81)) == []
    for bad in ("1.5", "-1.5", "abc"):
        assert _search(client, auth_headers, admin, query_image, min_similarity=bad).status_code == 422


# ------------------------------------------------------------------ a bad query image
def test_a_query_without_exactly_one_face_is_a_422_and_writes_no_log_row(
    client, db, auth_headers, admin, enrolled, query_image, fake_recognition, final_sha
):
    enrolled("Alpha Fictional", [[1, 0, 0, 0]])
    fake_recognition.set_faces(final_sha(query_image))                              # no face
    no_face = _search(client, auth_headers, admin, query_image)
    assert no_face.status_code == 422 and no_face.json()["error"]["message"] == "No face was found in the image"
    fake_recognition.set_faces(final_sha(query_image), [1, 0, 0, 0], [0, 1, 0, 0])  # two faces
    several = _search(client, auth_headers, admin, query_image)
    assert several.status_code == 422 and "More than one face" in several.json()["error"]["message"]
    assert _log_rows(db) == []


def test_an_invalid_query_image_is_refused_before_the_model_is_asked(
    client, auth_headers, admin, make_image_bytes, fake_recognition
):
    text = _search(client, auth_headers, admin, b"just some text, not a picture\n" * 10)
    gif = _search(client, auth_headers, admin, make_image_bytes("GIF"))
    tiny = _search(client, auth_headers, admin, make_image_bytes("PNG", size=(50, 50)))
    assert (text.status_code, gif.status_code, tiny.status_code) == (400, 415, 422)
    assert fake_recognition.calls == []
    missing = client.post("/search", headers=auth_headers(admin))
    assert missing.status_code == 422


