def test_search_is_admin_only(client, auth_headers, reporter, query_image, fake_recognition):
    anonymous = client.post("/search", files={"file": ("q.png", query_image, "image/png")})
    assert anonymous.status_code == 401
    assert _search(client, auth_headers, reporter, query_image).status_code == 403
    assert fake_recognition.calls == []


def test_search_without_a_model_answers_503_and_writes_nothing(
    client, db, auth_headers, admin, make_image_bytes
):
    response = _search(client, auth_headers, admin, make_image_bytes("PNG", size=(200, 200)))   # the real, unconfigured service
    assert response.status_code == 503
    assert response.json()["error"]["message"] == NOT_CONFIGURED
    assert _log_rows(db) == []
    assert db.scalar(select(func.count()).select_from(FaceEmbedding)) == 0


def test_the_response_carries_the_disclaimer_and_never_a_vector_or_a_confidence(
    client, auth_headers, admin, enrolled, query_image
):
    enrolled("Alpha Fictional", [[0.8, 0.6, 0, 0]], address="9 Hidden Street, Example Colony")
    response = _search(client, auth_headers, admin, query_image)
    body = response.json()
    assert set(body) == {"disclaimer", "model", "candidates_considered", "stale_embeddings_skipped", "results"}
    assert body["disclaimer"] == DISCLAIMER
    assert set(body["results"][0]) == {
        "rank", "similarity", "similarity_percent", "matched_photo_id", "case",
    }
    assert set(body["results"][0]["case"]) == {
        "id", "name", "age", "gender", "city", "state", "last_seen_date", "status",
    }
    assert body["results"][0]["case"]["status"] == "approved"
    assert not ({"vector", "embedding", "confidence", "probability", "contact_email", "contact_phone",
                 "address"} & _all_keys(body))
    for forbidden in ("vector", "confidence", "probability", "Hidden Street"):
        assert forbidden not in response.text, forbidden


def _all_keys(value) -> set:
    if isinstance(value, dict):
        return set(value) | {key for item in value.values() for key in _all_keys(item)}
    if isinstance(value, list):
        return {key for item in value for key in _all_keys(item)}
    return set()


# ------------------------------------------------------------------ the audit row and the logs
def test_every_successful_search_writes_one_log_row_without_any_image_data(
    client, db, auth_headers, admin, enrolled, query_image
):
    case_a, _ = enrolled("Alpha Fictional", [[0.8, 0.6, 0, 0]])
    enrolled("Beta Fictional", [[0.5, 0.8660254, 0, 0]])
    assert _search(client, auth_headers, admin, query_image, limit=20).status_code == 200
    assert _search(client, auth_headers, admin, query_image, min_similarity=0.99).status_code == 200

    first, second = _log_rows(db)
    assert (first.admin_id, first.result_count, first.top_case_id, first.top_similarity) == (admin.id, 2, case_a.id, 0.8)
    assert (first.model_name, first.model_version) == ("fake-face-model", "1")
    assert (second.result_count, second.top_case_id, second.top_similarity) == (0, None, None)
    columns = {column["name"] for column in inspect(engine).get_columns("face_search_logs")}
    assert columns == {
        "id", "admin_id", "searched_at", "result_count", "top_case_id", "top_similarity", "model_name", "model_version",
    }                                                                              # no image, no embedding, no query text


def test_search_logs_contain_ids_and_counts_only(client, auth_headers, admin, enrolled, query_image, caplog):
    enrolled("Zyxwv Personname", [[0.8, 0.6, 0, 0]])
    with caplog.at_level(logging.INFO):
        assert _search(client, auth_headers, admin, query_image).status_code == 200
    record = next(r for r in caplog.records if r.getMessage() == "face_search")
    assert record.admin_id == str(admin.id)
    assert (record.result_count, record.candidates_considered, record.stale_embeddings_skipped) == (1, 1, 0)
    for secret in ("Zyxwv", "Personname", "query-secret-name", "boss@example.com", "Sampletown", "Fictional Admin"):
        assert secret not in caplog.text, secret
        assert all(secret not in str(r.__dict__) for r in caplog.records), secret
